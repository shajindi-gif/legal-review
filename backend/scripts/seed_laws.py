async def seed() -> None:
    print("=" * 60)
    print("种子法规库导入")
    print("=" * 60)

    factory = get_session_factory()
    async with factory() as session:
        service = LegalLibraryService(session)
        succeeded = 0
        total_clauses = 0
        for law_data in SEED_LAWS:
            print(f"\n导入: {law_data['law_name']} ({law_data['version']})")
            req = LegalDocumentCreate(**law_data)
            try:
                law = await service.import_law(req)
                await session.commit()
                # 用 SQL 统计，避免 async session 访问 lazy 关系触发 MissingGreenlet
                from sqlalchemy import func, select
                from app.models.legal import LegalClause
                cnt_result = await session.execute(
                    select(func.count(), func.count(LegalClause.embedding))
                    .where(LegalClause.law_id == law.id)
                )
                clause_count, emb_count = cnt_result.one()
                print(f"  ✅ 成功: law_id={law.id}, 条款数={clause_count}, "
                      f"已生成 embedding={emb_count}/{clause_count}")
                succeeded += 1
                total_clauses += clause_count
            except Exception as e:
                await session.rollback()
                print(f"  ❌ 失败: {type(e).__name__}: {e}")

    print(f"\n{'=' * 60}")
    print(f"导入完成: {succeeded}/{len(SEED_LAWS)} 部法规, 共 {total_clauses} 条款")
    print("=" * 60)


if __name__ == "__main__":
    asyncio.run(seed())
